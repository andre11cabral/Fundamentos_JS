/* Criar uma função que dado dois valores (passados como parâmetros) mostre no console a soma, subtração, 
multiplicação e divisão desses valores. */

function valores(valor1, valor2) {
    console.log("Minha soma: ", valor1 + valor2); console.log("Minha subtração: ", valor1 - valor2); console.log("Minha multiplicação: ", valor1 * valor2); console.log("Minha divisão: ", valor1 / valor2);
}
valores(5, 5); 
